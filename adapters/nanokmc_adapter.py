def _read_nanokmc_cluster_distribution(path: Path) -> list[list[int]]:
    """Read NanoKMC evaluation/clusters_S0.csv for native diagnostic comparison."""
    if not path.exists():
        return []
    rows: list[list[int]] = []
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if not line.strip():
            continue
        parts = line.split(";")[1:]
        vals: list[int] = []
        for part in parts:
            part = part.strip()
            if not part:
                continue
            try:
                vals.append(int(float(part)))
            except ValueError:
                pass
        rows.append(vals)
    return rows


class NanoKMCAdapter(CodeAdapter):
    """Frozen six-path NanoKMC manuscript benchmark adapter."""

    MODE_INFO = {
        "active_filtered_generic": {
            "name": "nanokmc_active_filtered_generic",
            "system_id": "KMCActiveFilteredGeneric",
            "method_label": "NanoKMC Active-Filtered Generic",
        },
        "active_filtered_binary_nn": {
            "name": "nanokmc_active_filtered_binary_nn",
            "system_id": "KMCActiveFilteredBinaryNN",
            "method_label": "NanoKMC Active-Filtered BinaryNN",
        },
        "partial_filter_optimized": {
            "name": "nanokmc_partial_filter_optimized",
            "system_id": "KMCPartialFilterOptimized",
            "method_label": "partial structural filtering, optimized in-code reference",
        },
        "rate_category_optimized": {
            "name": "nanokmc_rate_category_optimized",
            "system_id": "KMCRateCategoryOptimized",
            "method_label": "coarse rate-category rejection, optimized in-code literature/reference implementation",
            "extra_input": "RateCategoryCount=4;",
        },
        "exact_class_optimized": {
            "name": "nanokmc_exact_class_optimized",
            "system_id": "KMCExactClassOptimized",
            "method_label": "exact finite-rate classes, optimized in-code reference",
        },
        "bit_encoded": {
            "name": "nanokmc_bit_encoded",
            "system_id": "KMCClassical",
            "method_label": "NanoKMC classical blind-proposal reference",
        },
    }

    def __init__(self, paths: dict, mode: str):
        super().__init__(paths)
        try:
            info = self.MODE_INFO[mode]
        except KeyError as exc:
            raise ValueError(mode) from exc
        self.mode = mode
        self.name = info["name"]
        self.system_id = info["system_id"]
        self.method_label = info["method_label"]
        self.extra_input = info.get("extra_input", "")

    def prepare(self, scenario: BenchmarkScenario, seed: int, run_dir: Path) -> None:
        run_dir.mkdir(parents=True, exist_ok=True)
        (run_dir / "output" / "bit").mkdir(parents=True, exist_ok=True)
        (run_dir / "evaluation").mkdir(parents=True, exist_ok=True)
        calcdata = "".join(f"{p};0;0;0;0;0;0;\n" for p in scenario.mcs_points)
        (run_dir / "output" / "CalcData.csv").write_text(calcdata, encoding="utf-8")
        (run_dir / "output" / "CalcData.template.csv").write_text(calcdata, encoding="utf-8")
        nanokmc_in = f'''// Generated by nanokmc-benchmarks
SystemID="{self.system_id}";
{self.extra_input}
Seed={seed};
SeedStart={seed};
SeedEnd={seed};
SeedStep=1;
NSpecies=2;
knx={scenario.nx};
kny={scenario.ny};
knz={scenario.nz};
lc=1.0;
kT={scenario.kT};
BondSize=0;
SpeciesName(1)="A";
SpeciesName(2)="B";
SpeciesColor(1)="[255,0,0]";
SpeciesColor(2)="[0,0,255]";
RasmolSpeciesPlot(1)=1;
RasmolSpeciesPlot(2)=1;
EvalParam=" Benchmark ClusterDistribution Rasmol ";
SysEvalParam=" ";
Index="StrCalcSystemID_IntCalcT_IntSysEB_IntSysdE_IntCalcSeed";
T=1000;
EB=1.0;
dE=0.0;
E01=0.0;
f01=1.0;
Ea={scenario.Ea};
dev=0.0;
clvl={scenario.composition_A};
Fluence=0;
'''
        (run_dir / "nanokmc.in").write_text(nanokmc_in, encoding="utf-8")

    def run(self, scenario: BenchmarkScenario, seed: int, run_dir: Path) -> None:
        exe = Path(self.paths["nanokmc_exe"])
        run_dir_msys = windows_path_to_msys(run_dir)
        exe_msys = windows_path_to_msys(exe)
        shell_cmd = f"cd '{run_dir_msys}' && '{exe_msys}'"
        cmd = msys2_bash_command(self.paths, shell_cmd)

        result = run_timed(cmd, cwd=run_dir, env=msys2_runtime_env(self.paths))
        (run_dir / "stdout.txt").write_text(result.stdout, encoding="utf-8", errors="ignore")
        (run_dir / "stderr.txt").write_text(result.stderr, encoding="utf-8", errors="ignore")
        (run_dir / "external_timing.json").write_text(json.dumps({
            "returncode": result.returncode,
            "wall_seconds": result.wall_seconds,
            "launch_mode": "msys2_bash",
            "command": cmd,
        }, indent=2), encoding="utf-8")
        if result.returncode != 0:
            hint = explain_windows_returncode(result.returncode)
            extra = f" ({hint})" if hint else ""
            raise RuntimeError(
                f"NanoKMC run failed for {self.name}: {result.returncode}{extra}. "
                f"See {run_dir / 'stderr.txt'}"
            )

    def collect(self, scenario: BenchmarkScenario, seed: int, run_dir: Path, out_dir: Path) -> None:
        out_dir.mkdir(parents=True, exist_ok=True)
        bench_path = run_dir / "evaluation" / "Benchmark.csv"
        if not bench_path.exists():
            raise FileNotFoundError(bench_path)
        df = pd.read_csv(bench_path, sep=";", engine="python")
        df.columns = [c.strip() for c in df.columns]
        timing = json.loads((run_dir / "external_timing.json").read_text(encoding="utf-8"))
        cluster_dist_rows_native = _read_nanokmc_cluster_distribution(
            run_dir / "evaluation" / "clusters_S0.csv"
        )
        max_native_time_ms = float(df["TimeMsCumulative"].max()) if "TimeMsCumulative" in df else 0.0
        periods = nanokmc_fcc_periods(scenario.nx, scenario.ny, scenario.nz)

        rows: list[dict] = []
        timing_rows: list[dict] = []
        manifest_rows: list[dict] = []
        distribution_rows: list[dict] = []
        accepted_cum = 0
        attempted_cum = 0
        reference_counts: tuple[int, int] | None = None

        for idx, row in df.iterrows():
            step = int(row.get("StepCount", row.get("CalcDataStep", 0)))
            accepted_cum += int(row.get("NAcceptedRecord", 0))
            attempted_cum += int(row.get("NJumpsRecord", 0))
            total_sites = int(row.get("TotalAtoms", scenario.nanokmc_total_sites_estimate))
            accepted_per_site = accepted_cum / total_sites if total_sites else 0.0

            post: dict = {}
            snap = read_nanokmc_rasmol_xyz(
                run_dir,
                step,
                geometry="fcc",
                coordination=12,
                periods=periods,
            )
            if snap is None:
                raise FileNotFoundError(f"NanoKMC snapshot missing at requested point {step}")
            else:
                try:
                    analysis = analyze_snapshot(snap)
                    post = analysis.metrics
                    counts = (analysis.validation.count_A, analysis.validation.count_B)
                    if reference_counts is None:
                        reference_counts = counts
                    elif counts != reference_counts:
                        raise ValueError(
                            f"NanoKMC composition changed across snapshots: "
                            f"initial A/B={reference_counts}, step {step}={counts}"
                        )

                    native_a = int(row.get("AtomNumber0", counts[0]))
                    native_b = int(row.get("AtomNumber1", counts[1]))
                    if counts != (native_a, native_b):
                        raise ValueError(
                            f"NanoKMC snapshot/native count mismatch at step {step}: "
                            f"snapshot A/B={counts}, Benchmark.csv species0/1={(native_a, native_b)}"
                        )

                    manifest = snapshot_manifest_row(snap, analysis)
                    manifest.update({
                        "scenario_id": scenario.id,
                        "code": self.name,
                        "seed": seed,
                        "save_index": idx,
                    })
                    manifest_rows.append(manifest)
                    distribution_rows.extend(cluster_distribution_rows(
                        analysis,
                        scenario_id=scenario.id,
                        code=self.name,
                        seed=seed,
                        save_index=idx,
                        native_step=step,
                    ))
                except Exception as exc:
                    raise ValueError(f"Invalid NanoKMC snapshot at requested point {step}") from exc

            process_seconds = float(row.get("TimeMsCumulative", 0.0)) / 1000.0
            common_mcs = float(row.get("CommonMCSExact", step))
            evolution_wall_seconds = float(row.get("EvolutionWallSecondsCumulative", 0.0))
            external_scaled = (
                timing["wall_seconds"] * (float(row.get("TimeMsCumulative", 0.0)) / max_native_time_ms)
                if max_native_time_ms else ""
            )

            # Preserve NanoKMC-native cluster evaluation only as an independent
            # diagnostic. Cross-code morphology uses the common snapshot layer.
            native_cluster_count = ""
            native_avg_cluster_size = ""
            native_largest_bin_upper = ""
            if idx < len(cluster_dist_rows_native):
                dist = cluster_dist_rows_native[idx]
                native_cluster_count = sum(dist)
                if native_cluster_count:
                    native_avg_cluster_size = float(row.get("AtomNumber0", 0.0)) / native_cluster_count
                for j, val in enumerate(dist):
                    if val:
                        native_largest_bin_upper = 10 * (j + 1)

            rows.append({
                "scenario_id": scenario.id,
                "code": self.name,
                "method_label": self.method_label,
                "seed": seed,
                "geometry": "fcc",
                "coordination": int(row.get("CoordinationNumber", 12)),
                "total_sites": total_sites,
                "composition_A": scenario.composition_A,
                "kT": scenario.kT,
                "Ea": scenario.Ea,
                "save_index": idx,
                "requested_mcs": step,
                "native_step": step,
                "native_mcs": step,
                "native_simulation_time": "",
                "common_mcs_equivalent": common_mcs,
                "physical_time_seconds": "",
                "attempted_exchanges_total": attempted_cum,
                "accepted_exchanges_total": accepted_cum,
                "accepted_exchanges_per_site": accepted_per_site,
                "code_kmc_time": "",
                "interface_density_native": row.get("InterfaceDensityFCC", ""),
                "cluster_count_native": native_cluster_count,
                "average_cluster_size_native": native_avg_cluster_size,
                "largest_cluster_size_native": native_largest_bin_upper,
                "largest_cluster_fraction_native": "",
                "calculation_cpu_seconds_cumulative": process_seconds,
                "evolution_wall_seconds_cumulative": evolution_wall_seconds,
                "diagnostic_runtime_seconds_cumulative": evolution_wall_seconds,
                "diagnostic_runtime_source": "NanoKMC clean steady-clock evolution wall timer",
                "spparks_loop_wall_seconds_total_run": "",
                "calculation_wall_seconds_total_run": float(timing.get("wall_seconds", 0.0)),
                "cumulative_total_seconds_native": process_seconds,
                "cumulative_compute_seconds_native": evolution_wall_seconds,
                "cumulative_wall_seconds_external": external_scaled,
                **post,
            })
            timing_rows.append({
                "scenario_id": scenario.id,
                "code": self.name,
                "seed": seed,
                "save_index": idx,
                "progress_native_mcs": step,
                "progress_common_mcs_equivalent": common_mcs,
                "progress_accepted_per_site": accepted_per_site,
                "external_wall_seconds_cumulative": external_scaled,
                "native_total_seconds_cumulative": process_seconds,
                "native_compute_seconds_cumulative": evolution_wall_seconds,
                "diagnostic_runtime_seconds_cumulative": evolution_wall_seconds,
                "diagnostic_runtime_source": "NanoKMC clean steady-clock evolution wall timer",
                "timing_source": "NanoKMC steady-clock evolution timer; process timer recorded separately",
            })

        write_metrics_csv(rows, out_dir / "metrics_common.csv")
        write_timing_csv(timing_rows, out_dir / "timing_common.csv")
        write_rows_csv(manifest_rows, out_dir / "snapshot_manifest_common.csv")
        write_rows_csv(distribution_rows, out_dir / "cluster_distribution_common.csv")
        (out_dir / "run_metadata.json").write_text(json.dumps({
            "adapter": self.name,
            "system_id": self.system_id,
            "run_dir": str(run_dir),
            "external_timing": timing,
            "common_snapshot": {
                "coordinate_convention": "integer doubled-FCC/parity-grid coordinates",
                "species_mapping": "A=NanoKMC species 0 (S0), B=NanoKMC species 1 (S1)",
                "periods": periods,
                "topology": "periodic FCC, 12 neighbors/site",
            },
        }, indent=2), encoding="utf-8")
